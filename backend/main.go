// @Summary Search
// @Produce json
// @Param q query string true "Search query"
// @Param language query string false "Language code (e.g. 'en')"
// @Success 200 {object} SearchResponse
// @Failure 422 {object} RequestValidationError
// @Router /api/search [get]
func apiSearch(w http.ResponseWriter, r *http.Request) {
	q := r.URL.Query().Get("q")
	language := r.URL.Query().Get("language")
	if language == "" {
		language = "en"
	}
	w.Header().Set("Content-Type", "application/json")

	if q == "" {
		w.WriteHeader(http.StatusUnprocessableEntity)
		message := "Field required: q"
		if err := json.NewEncoder(w).Encode(RequestValidationError{
			StatusCode: http.StatusUnprocessableEntity,
			Message:    &message,
			Detail: []ValidationError{
				{Loc: []interface{}{"query", "q"}, Msg: "Field required", Type: "missing"},
			},
		}); err != nil {
			log.Printf("writing search validation error: %v", err)
		}
		return
	}

	results, err := searchPages(r.Context(), q, language)
	if err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		return
	}
	countSearch(results)
	json.NewEncoder(w).Encode(SearchResponse{Data: results})
}

// maxJSONBody caps how much of a JSON request body is read, so a client can't make the server
// buffer an arbitrarily large payload. r.ParseForm already has its own 10 MB limit.
const maxJSONBody = 1 << 20 // 1 MB

// readCredentials reads the auth fields from either a JSON body or a form-encoded body.
// The simulator sends JSON first and only falls back to form data if that fails, so both
// have to work.
func readCredentials(w http.ResponseWriter, r *http.Request) (Credentials, error) {
	var c Credentials
	if mt, _, err := mime.ParseMediaType(r.Header.Get("Content-Type")); err == nil && mt == "application/json" {
		err := json.NewDecoder(http.MaxBytesReader(w, r.Body, maxJSONBody)).Decode(&c)
		return c, err
	}

	if err := r.ParseForm(); err != nil {
		return c, err
	}
	c.Username = r.FormValue("username")
	c.Email = r.FormValue("email")
	c.Password = r.FormValue("password")
	c.Password2 = r.FormValue("password2")
	return c, nil
}

// writeValidationError sends a 422 with the given message in the HTTPValidationError shape
// the OpenAPI spec uses.
func writeValidationError(w http.ResponseWriter, msg string) {
	w.WriteHeader(http.StatusUnprocessableEntity)
	if err := json.NewEncoder(w).Encode(HTTPValidationError{
		Detail: []ValidationError{{Loc: []interface{}{"body"}, Msg: msg, Type: "value_error"}},
	}); err != nil {
		log.Printf("writing validation error: %v", err)
	}
}

// setSessionCookie logs a user in by setting the session cookie. The cookie is signed with
// sessionKey to prevent tampering and holds the user's id and username, which identify the
// user in later requests. It is HttpOnly so JavaScript can't read it, SameSite=Lax so it is
// still sent on top-level navigations, and it expires when the browser session ends (no
// MaxAge or Expires). (gorilla/sessions would allow more, e.g. Redis or database-backed sessions.)
func setSessionCookie(w http.ResponseWriter, userID int, username string) error {
	encoded, err := sessionKey.Encode("session", map[string]interface{}{"user_id": userID, "username": username})
	if err != nil {
		return err
	}
	http.SetCookie(w, &http.Cookie{ //nolint:gosec // G124: Secure follows COOKIE_SECURE, the VM serves plain HTTP
		Name:     "session",
		Value:    encoded,
		Path:     "/",
		HttpOnly: true,
		Secure:   cookieSecure,
		SameSite: http.SameSiteLaxMode,
	})
	return nil
}

// maxUsernameLength keeps usernames well inside the session cookie size limit.
const maxUsernameLength = 30
const invalidBodyMessage = "Invalid request body"

// @Summary Register
// @Accept x-www-form-urlencoded
// @Produce json
// @Param username formData string true "Username"
// @Param email formData string true "Email"
// @Param password formData string true "Password"
// @Param password2 formData string false "Repeat password"
// @Success 200 {object} AuthResponse
// @Failure 422 {object} HTTPValidationError
// @Router /api/register [post]
func apiRegister(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "application/json")
	creds, err := readCredentials(w, r)
	if err != nil {
		writeValidationError(w, invalidBodyMessage)
		return
	}

	// Same checks and messages as the legacy Flask app. password2 is only compared when it
	// is sent, since the API spec doesn't require it.
	switch {
	case creds.Username == "":
		writeValidationError(w, "You have to enter a username")
		return
	case utf8.RuneCountInString(creds.Username) > maxUsernameLength:
		writeValidationError(w, "The username can be at most 30 characters")
		return
	case creds.Email == "" || !strings.Contains(creds.Email, "@"):
		writeValidationError(w, "You have to enter a valid email address")
		return
	case creds.Password == "":
		writeValidationError(w, "You have to enter a password")
		return
	case creds.Password2 != "" && creds.Password != creds.Password2:
		writeValidationError(w, "The two passwords do not match")
		return
	}

	hashedPassword, err := bcrypt.GenerateFromPassword([]byte(creds.Password), bcrypt.DefaultCost)
	if errors.Is(err, bcrypt.ErrPasswordTooLong) {
		writeValidationError(w, "The password can be at most 72 bytes")
		return
	}
	if err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		return
	}

	userID, err := createUser(r.Context(), creds.Username, creds.Email, hashedPassword)
	if errors.Is(err, errUserExists) {
		writeValidationError(w, "The username or email is already taken")
		return
	}
	if err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		return
	}
	registrationsTotal.Inc()

	// Log the new user in straight away, so they don't have to type their password again
	if err := setSessionCookie(w, userID, creds.Username); err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		return
	}

	statusCode := 200
	message := "User registered successfully"
	json.NewEncoder(w).Encode(AuthResponse{StatusCode: &statusCode, Message: &message})
}

// @Summary Login
// @Accept x-www-form-urlencoded
// @Produce json
// @Param username formData string true "Username"
// @Param password formData string true "Password"
// @Success 200 {object} AuthResponse
// @Failure 422 {object} HTTPValidationError
// @Router /api/login [post]
func apiLogin(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "application/json")
	creds, err := readCredentials(w, r)
	if err != nil {
		writeValidationError(w, invalidBodyMessage)
		return
	}

	if creds.Username == "" || creds.Password == "" {
		writeValidationError(w, "Missing required field")
		return
	}

	user, err := getUserByUsername(creds.Username)
	if err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		return
	}

	// user is nil when the username doesn't exist. Answer exactly like a wrong password,
	// so the response doesn't reveal which usernames are registered.
	if user == nil || bcrypt.CompareHashAndPassword([]byte(user.Password), []byte(creds.Password)) != nil {
		loginsTotal.WithLabelValues("failed").Inc()
		w.WriteHeader(http.StatusUnauthorized)
		statusCode := 401
		message := "Invalid username or password"
		json.NewEncoder(w).Encode(AuthResponse{StatusCode: &statusCode, Message: &message})
		return
	}

	if err := setSessionCookie(w, user.ID, user.Username); err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		return
	}

	loginsTotal.WithLabelValues("ok").Inc()
	statusCode := 200
	message := "Logged in successfully"
	json.NewEncoder(w).Encode(AuthResponse{StatusCode: &statusCode, Message: &message})
}

// @Summary Logout
// @Produce json
// @Success 200 {object} AuthResponse
// @Router /api/logout [get]
func apiLogout(w http.ResponseWriter, r *http.Request) {
	http.SetCookie(w, &http.Cookie{ //nolint:gosec // G124: Secure follows COOKIE_SECURE, the VM serves plain HTTP
		Name:     "session",
		Value:    "",
		Path:     "/",
		HttpOnly: true,
		Secure:   cookieSecure,
		SameSite: http.SameSiteLaxMode,
		MaxAge:   -1, // MaxAge -1 means delete the cookie immediately
	})

	// OpenAPI spec: 200 application/json with an AuthResponse, not a redirect
	statusCode := 200
	message := "Logged out successfully"
	w.Header().Set("Content-Type", "application/json")
	if err := json.NewEncoder(w).Encode(AuthResponse{StatusCode: &statusCode, Message: &message}); err != nil {
		log.Printf("writing logout response: %v", err)
	}
}

// writeAuthResponse sends an AuthResponse JSON body with the given status code and message.
// The caller sets the Content-Type header first.
func writeAuthResponse(w http.ResponseWriter, status int, message string) {
	w.WriteHeader(status)
	if err := json.NewEncoder(w).Encode(AuthResponse{StatusCode: &status, Message: &message}); err != nil {
		log.Printf("writing auth response: %v", err)
	}
}

// readPasswordChange reads the change-password fields from either a JSON body or a
// form-encoded body, like readCredentials does for login and register.
func readPasswordChange(w http.ResponseWriter, r *http.Request) (PasswordChange, error) {
	var c PasswordChange
	if mt, _, err := mime.ParseMediaType(r.Header.Get("Content-Type")); err == nil && mt == "application/json" {
		err := json.NewDecoder(http.MaxBytesReader(w, r.Body, maxJSONBody)).Decode(&c)
		return c, err
	}

	if err := r.ParseForm(); err != nil {
		return c, err
	}
	c.OldPassword = r.FormValue("old_password")
	c.NewPassword = r.FormValue("new_password")
	c.NewPassword2 = r.FormValue("new_password2")
	return c, nil
}

// @Summary Serve Change Password Page
// @Description Shows the change-password form to a logged-in user, and redirects to /login otherwise. Users flagged must_change_password are sent here by every other page.
// @Produce html
// @Success 200 {string} string "HTML"
// @Router /change-password [get]
func serveChangePasswordPage(w http.ResponseWriter, r *http.Request) {
	sessionUser := currentUser(r)
	if sessionUser == nil {
		http.Redirect(w, r, "/login", http.StatusSeeOther)
		return
	}
	user, err := getUserByUsername(sessionUser.Username)
	if err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		return
	}
	if user == nil {
		http.Redirect(w, r, "/login", http.StatusSeeOther)
		return
	}

	data := PageData{Title: "Change Password", User: user}
	if user.MustChangePassword {
		data.Flashes = []string{"Your login details may have been exposed in a data breach. You must choose a new password before you can use the site."}
	}
	w.Header().Set("Content-Type", contentTypeHTML)
	if err := pages["change-password"].ExecuteTemplate(w, "layout", data); err != nil {
		log.Printf("render change password page: %v", err)
	}
}

// @Summary Change password
// @Description Changes the password of the logged-in user and clears the must-change-password flag. The new password must differ from the old one.
// @Accept x-www-form-urlencoded
// @Produce json
// @Param old_password formData string true "Current password"
// @Param new_password formData string true "New password"
// @Param new_password2 formData string true "Repeat new password"
// @Success 200 {object} AuthResponse
// @Failure 401 {object} AuthResponse
// @Failure 422 {object} HTTPValidationError
// @Router /api/change-password [post]
func apiChangePassword(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "application/json")
	sessionUser := currentUser(r)
	if sessionUser == nil {
		writeAuthResponse(w, http.StatusUnauthorized, "You must be logged in to change your password")
		return
	}

	change, err := readPasswordChange(w, r)
	if err != nil {
		writeValidationError(w, invalidBodyMessage)
		return
	}

	// Read the user from the database rather than trusting the cookie, which only holds the
	// username. user is nil if the account was deleted after the cookie was issued.
	user, err := getUserByUsername(sessionUser.Username)
	if err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		return
	}
	if user == nil {
		writeAuthResponse(w, http.StatusUnauthorized, "You must be logged in to change your password")
		return
	}

	switch {
	case change.OldPassword == "" || change.NewPassword == "" || change.NewPassword2 == "":
		writeValidationError(w, "Missing required field")
		return
	case change.NewPassword != change.NewPassword2:
		writeValidationError(w, "The two new passwords do not match")
		return
	case change.NewPassword == change.OldPassword:
		// The old password may be the one that leaked, so it must not be reused.
		writeValidationError(w, "The new password must be different from the old one")
		return
	}

	if bcrypt.CompareHashAndPassword([]byte(user.Password), []byte(change.OldPassword)) != nil {
		writeValidationError(w, "The old password is incorrect")
		return
	}

	hashedPassword, err := bcrypt.GenerateFromPassword([]byte(change.NewPassword), bcrypt.DefaultCost)
	if errors.Is(err, bcrypt.ErrPasswordTooLong) {
		writeValidationError(w, "The password can be at most 72 bytes")
		return
	}
	if err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		return
	}

	if err := updatePassword(r.Context(), user.ID, hashedPassword); err != nil {
		w.WriteHeader(http.StatusInternalServerError)
		return
	}

	writeAuthResponse(w, http.StatusOK, "Password changed successfully")
}

// passwordChangeAllowed lists the paths a user who must change their password can still reach:
// the change-password page and API, logging in and out, and the static files the page needs.
func passwordChangeAllowed(path string) bool {
	switch path {
	case "/change-password", "/api/change-password", "/api/login", "/api/logout":
		return true
	}
	return strings.HasPrefix(path, "/static/")
}

// requirePasswordChange wraps the router. A logged-in user flagged must_change_password (for
// example because their credentials leaked) can reach nothing but the change-password page until
// they have chosen a new password: pages redirect there, and API calls get 403. The flag is read
// from the database on every request instead of from the session cookie, so it also stops a
// session that was already open when the account was flagged.
func requirePasswordChange(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if passwordChangeAllowed(r.URL.Path) {
			next.ServeHTTP(w, r)
			return
		}
		sessionUser := currentUser(r)
		if sessionUser == nil {
			next.ServeHTTP(w, r)
			return
		}

		user, err := getUserByUsername(sessionUser.Username)
		if err != nil {
			log.Printf("check must_change_password for %q: %v", sessionUser.Username, err)
			w.WriteHeader(http.StatusInternalServerError)
			return
		}
		if user == nil || !user.MustChangePassword {
			next.ServeHTTP(w, r)
			return
		}

		if strings.HasPrefix(r.URL.Path, "/api/") {
			w.Header().Set("Content-Type", "application/json")
			writeAuthResponse(w, http.StatusForbidden, "You must change your password before you can use the site")
			return
		}
		http.Redirect(w, r, "/change-password", http.StatusSeeOther)
	})
}

func newMux() http.Handler {
	mux := http.NewServeMux()

	// Serve /static/* (CSS, images, osv) from ../frontend/static
	mux.Handle("GET /static/", http.StripPrefix("/static/", http.FileServer(http.Dir("../frontend/static"))))

	mux.HandleFunc("GET /", serveRootPage)
	mux.HandleFunc("GET /weather", serveWeatherPage)
	mux.HandleFunc("GET /register", serveRegisterPage)
	mux.HandleFunc("GET /login", serveLoginPage)
	mux.HandleFunc("GET /about", serveAboutPage)

	mux.HandleFunc("GET /api/search", apiSearch)
	mux.HandleFunc("GET /api/weather", apiWeatherHandler)
	mux.HandleFunc("POST /api/register", apiRegister)
	mux.HandleFunc("POST /api/login", apiLogin)
	mux.HandleFunc("GET /api/logout", apiLogout)
	mux.HandleFunc("GET /change-password", serveChangePasswordPage)
	mux.HandleFunc("POST /api/change-password", apiChangePassword)

	// Swagger UI endpoint
	mux.Handle("GET /swagger/", httpSwagger.WrapHandler)

	mux.HandleFunc("GET /health", serveHealth)

	return instrument(requirePasswordChange(mux))
}

// @Summary Health check
// @Description Returns 200 when the app is running and the database answers, 503 otherwise.
// @Produce json
// @Success 200 {object} map[string]string
// @Failure 503 {object} map[string]string
// @Router /health [get]
func serveHealth(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "application/json")
	status, body := http.StatusOK, map[string]string{"status": "ok"}
	if err := db.PingContext(r.Context()); err != nil {
		log.Printf("health check: database ping failed: %v", err)
		status, body = http.StatusServiceUnavailable, map[string]string{"status": "database unavailable"}
	}
	w.WriteHeader(status)
	if err := json.NewEncoder(w).Encode(body); err != nil {
		log.Printf("writing health response: %v", err)
	}
}

// @title WhoKnows API
// @version 0.1.0
// @description API for søgning, login og vejr i WhoKnows-projektet.
// @host localhost:8080
// @BasePath /
func main() {
	if err := godotenv.Load(); err != nil {
		log.Println("no .env file found, relying on process environment")
	}
	sessionKey = loadSessionKey()
	cookieSecure = os.Getenv("COOKIE_SECURE") == "true"

	// Initialize the database connection and ensure the schema is applied.
	// The db variable is a global handle to the SQLite database, which is used by the API handlers to perform queries and updates.
	db = initDB()
	// defer meaning: ensures that the database connection is closed when the main function exits, preventing resource leaks.
	defer func() {
		if err := db.Close(); err != nil {
			log.Printf("closing database: %v", err)
		}
	}()

	mux := newMux()

	// /metrics runs on its own internal port, next to the site (see metricsAddr)
	metricsServer := newMetricsServer()
	go func() {
		fmt.Printf("Metrics on %s/metrics\n", metricsServer.Addr)
		if err := metricsServer.ListenAndServe(); err != nil {
			log.Printf("metrics server stopped: %v", err)
		}
	}()

	fmt.Println("Server running on :8080")
	http.ListenAndServe(":8080", mux)
}
